"""Build a patch compliance report (Markdown) from results.csv.

Independent portfolio demo. Synthetic lab hosts. Standard library only.
Usage: python3 build_report.py sample-results.csv > sample-compliance-report.md
"""
import csv
import sys
from collections import Counter


def load(path):
    with open(path, newline="") as f:
        return list(csv.DictReader(f))


def family(os_name):
    return "Windows" if "Windows" in os_name else "Linux"


def summarise(rows):
    total = len(rows)
    ok = sum(1 for r in rows if r["result"] == "compliant")
    by_family = Counter()
    ok_family = Counter()
    for r in rows:
        fam = family(r["os"])
        by_family[fam] += 1
        if r["result"] == "compliant":
            ok_family[fam] += 1
    return {
        "total": total,
        "compliant": ok,
        "percent": round(100 * ok / total, 1) if total else 0.0,
        "families": {f: (ok_family[f], n) for f, n in sorted(by_family.items())},
        "attention": [r for r in rows if r["result"] != "compliant"],
    }


def render(rows):
    s = summarise(rows)
    out = [
        "# Patch compliance report (sample)",
        "",
        "> Independent portfolio demo. Synthetic lab hosts, generated by `build_report.py`.",
        "",
        f"**Overall compliance: {s['percent']}%** ({s['compliant']} of {s['total']} hosts)",
        "",
        "| OS family | Compliant | Total | % |",
        "|---|---|---|---|",
    ]
    for fam, (ok, n) in s["families"].items():
        out.append(f"| {fam} | {ok} | {n} | {round(100 * ok / n, 1)} |")
    out += ["", "## Hosts needing attention", ""]
    if not s["attention"]:
        out.append("None.")
    else:
        out += ["| Host | OS | Before | After | Likely reason |", "|---|---|---|---|---|"]
        for r in s["attention"]:
            reason = "Version unchanged - patch or reboot not applied" if r["before"] == r["after"] else "Post-check failed"
            out.append(f"| {r['host']} | {r['os']} | {r['before']} | {r['after']} | {reason} |")
    out += ["", "## All hosts", "", "| Host | Date | OS | Before | After | Result |", "|---|---|---|---|---|---|"]
    for r in rows:
        out.append(f"| {r['host']} | {r['date']} | {r['os']} | {r['before']} | {r['after']} | {r['result']} |")
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    print(render(load(sys.argv[1] if len(sys.argv) > 1 else "sample-results.csv")), end="")
